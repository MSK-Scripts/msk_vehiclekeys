const STRINGS: Record<AdminLocale, AdminStrings> = { de, en, hu }

export function strings(locale: string): AdminStrings {
  return STRINGS[(locale as AdminLocale)] || STRINGS.de
}

// Display names for the language dropdown. Locale codes come from the server
// (translation.lua); unknown codes fall back to their uppercased code.
const LOCALE_LABELS: Record<string, string> = {
  de: 'Deutsch',
  en: 'English',
  hu: 'Magyar',
}

export function localeLabel(code: string): string {
  return LOCALE_LABELS[code] || code.toUpperCase()
}

export function permLabel(t: AdminStrings, key: string): string {
  const k = ('perm_' + key.replace(/\./g, '_')) as keyof AdminStrings
  return (t[k] as string) || key
}

const ERR_KEYS: Record<string, keyof AdminStrings> = {
  no_permission: 'no_permission',
  bad_input: 'err_bad_input',
  not_found: 'err_not_found',
  player_offline: 'err_player_offline',
  same_plate: 'err_same_plate',
  bad_id: 'err_bad_id',
  bad_coords: 'err_bad_coords',
  bad_name: 'err_bad_name',
  protected: 'err_protected',
  blacklisted: 'err_blacklisted',
}

export function errText(t: AdminStrings, err?: string): string {
  if (!err) return t.error
  const k = ERR_KEYS[err]
  return k ? (t[k] as string) : `${t.error}: ${err}`
}
